-- ============================================================================
-- Healthcare MVT
-- Initial database schema
--
-- This migration represents the JPA entities currently implemented:
--   1. Permission
--   2. Role
--   3. User
--   4. CarePartnerProfile
--   5. PatientProfile
--   6. Role-Permission join table
--
-- Future domains such as hospitals, departments, appointments, AYUSH
-- applications, airport services and translations are intentionally excluded.
-- ============================================================================


-- ============================================================================
-- PERMISSIONS
-- ============================================================================

CREATE TABLE permissions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,

    created_by  VARCHAR(255),
    updated_by  VARCHAR(255),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted  BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_permissions_name UNIQUE (name)
);


-- ============================================================================
-- ROLES
-- ============================================================================

CREATE TABLE roles
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,

    created_by  VARCHAR(255),
    updated_by  VARCHAR(255),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted  BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_roles_name UNIQUE (name)
);


-- ============================================================================
-- ROLE-PERMISSION JOIN TABLE
--
-- This table is mapped by Role.permissions through @ManyToMany and @JoinTable.
-- It is not a separate audited JPA entity in the current implementation.
-- ============================================================================

CREATE TABLE role_permissions
(
    role_id       BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,

    CONSTRAINT pk_role_permissions
        PRIMARY KEY (role_id, permission_id),

    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (role_id)
            REFERENCES roles (id),

    CONSTRAINT fk_role_permissions_permission
        FOREIGN KEY (permission_id)
            REFERENCES permissions (id)
);


CREATE INDEX idx_role_permissions_permission_id
    ON role_permissions (permission_id);


-- ============================================================================
-- USERS
-- ============================================================================

CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,

    title         VARCHAR(10),
    first_name    VARCHAR(100) NOT NULL,
    middle_name   VARCHAR(100),
    last_name     VARCHAR(100) NOT NULL,

    role_id       BIGINT,

    created_by    VARCHAR(255),
    updated_by    VARCHAR(255),
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted    BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_users_email UNIQUE (email),

    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id)
            REFERENCES roles (id)
);


CREATE INDEX idx_users_role_id
    ON users (role_id);


-- ============================================================================
-- CARE PARTNER PROFILES
-- ============================================================================

CREATE TABLE care_partner_profiles
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    user_id                     BIGINT NOT NULL,
    partner_id                  VARCHAR(255) NOT NULL,

    company_name                VARCHAR(255),
    country                     VARCHAR(255),
    trade_license               VARCHAR(255),
    gst_number                  VARCHAR(255),
    passport_number             VARCHAR(255),

    verification_document_url   VARCHAR(255) NOT NULL,

    approval_status             VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    approved_by                 BIGINT,
    approved_at                 TIMESTAMP,
    rejection_reason            VARCHAR(255),

    created_by                  VARCHAR(255),
    updated_by                  VARCHAR(255),
    created_at                  TIMESTAMP,
    updated_at                  TIMESTAMP,
    is_active                   BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted                  BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_care_partner_profiles_user_id
        UNIQUE (user_id),

    CONSTRAINT uk_care_partner_profiles_partner_id
        UNIQUE (partner_id),

    CONSTRAINT fk_care_partner_profiles_user
        FOREIGN KEY (user_id)
            REFERENCES users (id),

    CONSTRAINT chk_care_partner_approval_status
        CHECK (
            approval_status IN ('PENDING', 'APPROVED', 'REJECTED')
            )
);


-- ============================================================================
-- PATIENT PROFILES
--
-- The current PatientProfile entity does not explicitly provide @Table.
-- Its expected physical table name under Spring/Hibernate snake-case naming
-- is patient_profile.
-- ============================================================================

CREATE TABLE patient_profile
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    user_id                   BIGINT,
    patient_id                VARCHAR(255) NOT NULL,

    country                   VARCHAR(255),
    national_id               VARCHAR(255),
    passport_number           VARCHAR(255),

    referred_by_partner_id    BIGINT,

    created_by                VARCHAR(255),
    updated_by                VARCHAR(255),
    created_at                TIMESTAMP,
    updated_at                TIMESTAMP,
    is_active                 BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted                BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_patient_profile_user_id
        UNIQUE (user_id),

    CONSTRAINT uk_patient_profile_patient_id
        UNIQUE (patient_id),

    CONSTRAINT fk_patient_profile_user
        FOREIGN KEY (user_id)
            REFERENCES users (id),

    CONSTRAINT fk_patient_profile_referring_partner
        FOREIGN KEY (referred_by_partner_id)
            REFERENCES care_partner_profiles (id)
);


CREATE INDEX idx_patient_profile_referred_by_partner_id
    ON patient_profile (referred_by_partner_id);


